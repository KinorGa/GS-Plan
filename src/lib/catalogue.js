// Catalogue access for the team builder.
//
// Loads the two JSON catalogues the UI needs to populate its pickers and
// indexes them for lookup:
//
//   /data/charlist.json   every character, keyed by id
//   /data/weaponlist.json every weapon, keyed by id
//
// Both are fetched ONCE and cached in a module-level promise, because the
// builder mounts a card per team slot and each one would otherwise re-request
// the same 190 KB. The promise (not the data) is cached so concurrent callers
// share a single in-flight request instead of racing.

import { useCallback, useEffect, useState } from 'react';
import { createPromiseCache, fetchJson, fetchJsonOrThrow } from './json-cache';

const CATALOGUE = {
  charlist: '/data/charlist.json',
  weaponlist: '/data/weaponlist.json',
};

/**
 * The stat FACTORS: base values, growth curves and ascension bonuses.
 *
 * Generated by `npm run stats:update` (see scripts/build-stats.mjs). Loaded here
 * because `derivePanel` is synchronous and pure -- a panel must not depend on a
 * request that may still be in flight -- so every caller that derives a panel
 * already threads the catalogue through.
 *
 * OPTIONAL ON PURPOSE. The app must still render if the file is absent (an old
 * checkout, a build that predates it): `derivePanel` falls back to the rounded
 * per-level tables in the character detail file, which is what it always used.
 */
const STATS_URL = '/data/stats-compact.json';

const cache = createPromiseCache();

/**
 * Discard the cached catalogue so the next `loadCatalogue()` refetches.
 *
 * Needed because the cache holds the PROMISE, and a rejected promise is still a
 * promise: without this, one transient failure left the picker permanently
 * empty for the life of the page, with a full reload the only way out. (The
 * cache also drops rejections on its own; this is the explicit escape hatch for
 * a user-pressed Retry.)
 */
export function invalidateCatalogue() {
  cache.invalidate();
}

/**
 * Is this catalogue entry one a user can actually play?
 *
 * A character ALWAYS has an element, so `element === 'Unknown'` is never a real
 * value -- it marks a record the dataset does not have complete data for.
 * Measured against the catalogue, it matches EXACTLY three entries and no more:
 *
 *   10000117  奇偶·男性    a test placeholder: no constellations, a passives
 *   10000118  奇偶·女性    object holding one blank slot
 *   10000134  旅行者       a STUB: no detail file at all, and a
 *                          `WEAPON_CROSSBOW` type that is not in the weapon table
 *
 * All three are unconfigurable, and the Traveler stub is also a duplicate --
 * `10000005_*` and `10000007_*` are the fourteen real Traveler entries, one per
 * element, every one of them complete. Dropping the stub leaves those intact.
 *
 * WHY NOT ALSO REQUIRE `QUALITY_ORANGE_SP`, WHICH IS WHAT THIS USED TO DO
 *   The intersection (Unknown AND ORANGE_SP) is a SUBSET of Unknown alone, so it
 *   dropped the two placeholders and wrongly KEPT the broken Traveler stub. It
 *   was believed to be necessary because "element === 'Unknown' alone also
 *   matches 旅行者" -- true, but the Traveler it matches is the stub, not the
 *   fourteen real ones. That reasoning was wrong and is recorded here so it is
 *   not re-derived.
 *
 *   `QUALITY_ORANGE_SP` alone is genuinely wrong: it also matches 埃洛伊 (Aloy),
 *   who is a real, complete character.
 *
 * Detected by evidence rather than by hardcoding the ids, so a future incomplete
 * record with the same signature is caught the same way.
 *
 * EXPORTED because it is a fact about the DATASET, not about this loader: the
 * buff library's source index reads `charlist.json` directly and has to drop the
 * same entries, or the editor would list fillable rows for characters that do
 * not exist.
 */
export const isPlaceholderChar = (c) => c.element === 'Unknown';

/** Fetch and index both catalogues. Resolves to a `Catalogue` object. */
export function loadCatalogue() {
  return cache.get('catalogue', async () => {
    // The three files are fetched together, not in sequence. The stat factors
    // are allowed to be missing (`fetchJson` resolves to null rather than
    // throwing); the two catalogues are not.
    const [rawChars, weapons, stats] = await Promise.all([
      fetchJsonOrThrow(CATALOGUE.charlist),
      fetchJsonOrThrow(CATALOGUE.weaponlist),
      fetchJson(STATS_URL),
    ]);

    // Dropped once, here, so no consumer has to remember to filter: the picker
    // grid, the planner's character menu and the buff-source builder all read
    // this map.
    const chars = Object.fromEntries(
      Object.entries(rawChars).filter(([, c]) => !isPlaceholderChar(c))
    );

    // Weapons indexed by the type they are wielded as, so the picker for a
    // character only offers weapons they can actually equip.
    const weaponsByType = {};
    for (const [id, w] of Object.entries(weapons)) {
      (weaponsByType[w.weaponType] ||= []).push({ id, ...w });
    }
    // Best first: a 5-star is what a team builder reaches for far more often
    // than a 3-star, and the list is 257 entries long.
    const RARITY = { QUALITY_ORANGE: 0, QUALITY_PURPLE: 1, QUALITY_BLUE: 2, QUALITY_GREEN: 3 };
    for (const list of Object.values(weaponsByType)) {
      list.sort((a, b) =>
        (RARITY[a.qualityType] ?? 9) - (RARITY[b.qualityType] ?? 9) ||
        a.enName.localeCompare(b.enName)
      );
    }

    return { chars, weapons, weaponsByType, stats };
  });
}

/**
 * React binding for the catalogue.
 *
 * Returns `{ catalogue, error, loading, retry }`. The catalogue is `null` until
 * it resolves, so callers must handle the loading state rather than assuming a
 * populated list.
 *
 * `retry` re-attempts after a failure. A page reload used to be the only way
 * back from a transient network error.
 */
export function useCatalogue() {
  const [catalogue, setCatalogue] = useState(null);
  const [error, setError] = useState(null);
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    let alive = true;
    setError(null);
    loadCatalogue()
      .then((c) => alive && setCatalogue(c))
      .catch((e) => alive && setError(e.message));
    return () => { alive = false; };
  }, [attempt]);

  const retry = useCallback(() => {
    invalidateCatalogue();
    setCatalogue(null);
    setAttempt((n) => n + 1);
  }, []);

  return { catalogue, error, loading: !catalogue && !error, retry };
}

/** Characters as a sorted array, for rendering a picker grid. */
export function useCharacters() {
  const { catalogue, error, loading, retry } = useCatalogue();
  const chars = catalogue
    ? Object.entries(catalogue.chars)
        .map(([id, c]) => ({ id, ...c }))
        .sort(
          (a, b) =>
            (a.qualityType === 'QUALITY_ORANGE' ? 0 : 1) -
              (b.qualityType === 'QUALITY_ORANGE' ? 0 : 1) ||
            (a.enName || '').localeCompare(b.enName || '')
        )
    : [];
  return { chars, error, loading, retry };
}

/* ------------------------------------------------------- character details */

/**
 * Cache of per-character detail files, keyed by `lang/id`.
 *
 * Every card loads its character's detail file for the talent icons and the
 * constellations. Two cards showing the same character therefore requested the
 * same ~80 KB file twice, which is pure waste and grows with the team size.
 * Keying by language too means switching language refetches rather than
 * serving icons from the wrong locale.
 *
 * The MODEL, not the data: callers get the promise and can hold their own
 * loading state, so a component that unmounts mid-flight does not leak.
 */
const detailCache = new Map();

/** Fetch one character's detail file, reusing an in-flight or settled request. */
export function loadCharacterDetail(charId, lang) {
  const key = `${lang}/${charId}`;
  if (detailCache.has(key)) return detailCache.get(key);

  const p = fetchJson(`/data/char/${lang}/${charId}.json`).catch(() => {
    // A failure must not be cached, or one transient blip would leave that
    // character permanently icon-less for the life of the page.
    detailCache.delete(key);
    return null;
  });

  detailCache.set(key, p);
  return p;
}

/**
 * React binding for one character's detail file.
 *
 * Returns `null` while loading and on failure, which is what every consumer
 * wants: the card draws its placeholder rows and fills them in when the icons
 * arrive.
 */
export function useCharacterDetail(charId, lang) {
  const [detail, setDetail] = useState(null);

  useEffect(() => {
    if (!charId) { setDetail(null); return; }
    let alive = true;
    setDetail(null);
    loadCharacterDetail(charId, lang).then((d) => { if (alive) setDetail(d); });
    return () => { alive = false; };
  }, [charId, lang]);

  return detail;
}

/**
 * A weapon's icon name as stored on disk.
 *
 * The catalogue says `UI_EquipIcon_*` while the downloaded file is
 * `UI_Gacha_EquipIcon_*` (a `Gacha_` infix is inserted). Verified against the
 * live site's own requests; see docs/FETCHING.md.
 */
export const weaponIconName = (weaponIcon) =>
  String(weaponIcon || '').replace(/^UI_(EquipIcon_)/, 'UI_Gacha_$1');

/* --------------------------------------------------------------- constants */

/**
 * Character level 1..100.
 *
 * The data table runs to 100 (Ascension 6) and the level control now goes all the
 * way, rather than stopping at 90 on the assumption that a released character
 * caps there. A build may legitimately be planned past 90, and clamping the
 * control made those levels unreachable while the data behind them already
 * existed.
 *
 * THE STEP IS 5, NOT 10, because 95 is a real level.
 *
 * Above 90 the table contains only 95 and 100 -- levels 91-94 and 96-99 are
 * absent for all 138 characters -- which is exactly the shape a step of 10 cannot
 * express: anchored at 100 it produces 100, 90, 80..., so 95 was unreachable and
 * the control would jump straight past the last ascension. A step of 5 gives
 * 100, 95, 90, 85..., every one of which exists.
 */
export const CHAR_LEVEL_MIN = 1;
export const CHAR_LEVEL_MAX = 100;
export const CHAR_LEVEL_STEP = 5;

/** Talent level 1..15. */
export const TALENT_MIN = 1;
export const TALENT_MAX = 15;

/**
 * The ascension phase a character level falls in.
 *
 * Read from the character's own `info.attributes` table rather than hardcoded,
 * because the bands differ by rarity: a 5-star ascends at 20/40/50/60/70/80
 * while a 4-star stops at 80 total. The table already encodes that, so deriving
 * it here keeps one source of truth and makes the level control honest about
 * what a given level actually implies.
 *
 * @returns {number} 0..6, or 0 when the table is missing.
 */
export function ascensionPhaseFor(detail, level) {
  const rows = detail?.info?.attributes;
  if (!Array.isArray(rows) || !rows.length) return 0;
  const row = rows.find((r) => r.level === level);
  return row?.ascension ?? 0;
}

/**
 * A character's six constellations, in order, with their own icons.
 *
 * Each constellation has a distinct emblem in the game, which is what makes
 * click-to-light meaningful: the row shows WHICH constellations are unlocked,
 * not just how many.
 */
export function constellationsOf(detail) {
  const c = detail?.constellations;
  if (!c) return [];
  return Object.keys(c)
    // Keys are `const1`..`const6`; sorting by the trailing number is what keeps
    // C1 first even though an object's key order is not guaranteed to be
    // insertion order for numeric-looking keys.
    .sort((a, b) => (parseInt(a.replace(/\D+/g, ''), 10) || 0) - (parseInt(b.replace(/\D+/g, ''), 10) || 0))
    .map((k) => c[k])
    .filter(Boolean);
}

/** Weapon refinement options R1..R5, for the dropdown. */
export const REFINE_OPTIONS = Array.from({ length: 5 }, (_, i) => ({
  value: i + 1,
  label: `R${i + 1}`,
}));
